-- ------------------------------------------------------------
-- DELIVERY ACCESS
-- The file may be stored before payment, but the customer is not
-- allowed to read it until payment is confirmed. Admin/worker can read.
-- ------------------------------------------------------------
drop policy if exists "delivery files read allowed" on storage.objects;
create policy "delivery files read allowed"
on storage.objects for select to authenticated
using (
  bucket_id='deliveries'
  and (
    public.is_admin()
    or public.is_worker()
    or exists(
      select 1 from public.projects pr
      where pr.user_id=auth.uid()
        and pr.delivery_path=storage.objects.name
        and pr.payment_status='confirmed'
    )
  )
);
